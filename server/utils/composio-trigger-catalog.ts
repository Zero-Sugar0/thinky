/** Lowercase, underscore-free key so "LAUNCH_DARKLY", "launchdarkly" and "launch_darkly" match. */
export function normalizeToolkitKey(slug: string): string {
  return slug.replace(/_/g, "").toLowerCase();
}

const catalogByKey = new Map(
  COMPOSIO_TRIGGER_CATALOG.map(entry => [normalizeToolkitKey(entry.toolkit), entry]),
);

export function findTriggerCatalogEntry(toolkitSlug: string): ComposioTriggerCatalogEntry | undefined {
  return catalogByKey.get(normalizeToolkitKey(toolkitSlug));
}

export function isSupportedTrigger(slug: string): boolean {
  return COMPOSIO_TRIGGER_CATALOG.some(entry => entry.triggers.includes(slug));
}
